-- 采购申请单状态统一迁移：老状态(待审批/已审批) -> 统一状态机(待审核/已生效)
-- 背景：全系统单据状态机已统一为 草稿->待审核->已生效，采购申请单后端此前仍写入老状态，
-- 导致 1) 采购合同选单(按 status='已生效' 过滤)查不到采购申请单 2) 前端按钮状态机制不同步。
-- 后端代码已改为写新状态并兼容读老状态；本脚本将存量数据一次性迁移到新状态。幂等可重复执行。
UPDATE purchase_request SET status = '待审核' WHERE status = '待审批';
UPDATE purchase_request SET status = '已生效' WHERE status = '已审批';
