-- 提成率配置历史留痕表 - H2 兼容版本
CREATE TABLE IF NOT EXISTS commission_rate (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no      INTEGER NOT NULL,
    basis           VARCHAR(20) NOT NULL DEFAULT 'order',
    base_rate       DECIMAL(6,4) NOT NULL,
    over_achievement_multiplier DECIMAL(5,2) NOT NULL DEFAULT 1.20,
    over_achievement_bonus       DECIMAL(6,4) NOT NULL DEFAULT 0.0300,
    effective_date  DATE NOT NULL,
    expiry_date     DATE,
    is_current      SMALLINT NOT NULL DEFAULT 0,
    remark          VARCHAR(500),
    created_by      VARCHAR(50),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_commission_rate_effective ON commission_rate(effective_date);
CREATE INDEX IF NOT EXISTS idx_commission_rate_current ON commission_rate(is_current);

